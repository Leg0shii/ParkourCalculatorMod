"""In-process bridge with the `JavaCompiler` methods, budgets and replies.

Coefficients come from tables generated by the Java bridge; scene checks and
footprints are Python ports of its finite-scene contract. There is no worker
process: a call either answers within its budget or raises `TimeoutError`.
"""
import hashlib
from pathlib import Path
import time

from parkour_solver.bridge.compiler import coefficient_request
from parkour_solver.physics import _coefficient_tables
from parkour_solver.physics.coefficients import compile_request
from parkour_solver.scene.geometry import route_footprints
from parkour_solver.scene.static_collision import check_scene


class PythonCompiler:
    def compile(self, route, plan, seconds):
        return self._exchange(coefficient_request(route, plan), seconds)

    def derive_footprints(self, route, seconds):
        return self._exchange({'action': 'footprints', 'blocks': route['blocks']}, seconds)['footprints']

    def derive_standing_footprints(self, route, seconds):
        return self._exchange({'action': 'standingFootprints', 'blocks': route['blocks']}, seconds)['footprints']

    def check_scene(self, scene, positions, movement, ground, seconds, contacts=None, **contract):
        if set(contract) - {'sneak', 'ladderTicks', 'velocities', 'friction'}:
            raise ValueError('Unsupported scene contract')
        return self._exchange(dict({'action': 'sceneCheck', 'scene': scene, 'positions': positions,
                               'movement': movement, 'expectedGround': ground, 'contacts': contacts or []}, **contract), seconds)

    def _exchange(self, message, seconds):
        deadline = time.monotonic() + seconds
        action = message.get('action')
        try:
            if action == 'sceneCheck':
                result = check_scene(message, deadline)
            elif action in ('footprints', 'standingFootprints'):
                result = {'footprints': route_footprints(message['blocks'], action == 'standingFootprints'),
                          'geometryModel': 'ConstraintDeriver.deriveFootprint:legacy'}
            else:
                result = compile_request(message)
        except (TypeError, KeyError, IndexError, AttributeError) as error:
            # The Java bridge reports any malformed request as an error reply.
            raise ValueError(f'{type(error).__name__}: {error}') from error
        if time.monotonic() > deadline:
            raise TimeoutError('Movement coefficient compilation exceeded the budget')
        return result

    def provenance(self):
        return dict(bridge='python', coefficientTables=hashlib.sha256(
            Path(_coefficient_tables.__file__).read_bytes()).hexdigest())

    def close(self):
        pass

    def __enter__(self):
        return self

    def __exit__(self, *args):
        self.close()
