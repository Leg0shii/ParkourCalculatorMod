"""Regenerate current code/function/document/file navigation (not archived content)."""
import ast
from collections import defaultdict
import os
from pathlib import Path
import subprocess

from tools.paths import STANDALONE_ROOT


def files():
    # Include deliberately new files, excluding ignored local runs/build/cache.
    result = subprocess.check_output(['git', 'ls-files', '-z', '--cached', '--others', '--exclude-standard', '--', '.'],
                                     cwd=STANDALONE_ROOT)
    return sorted({Path(p) for p in os.fsdecode(result).split('\0') if p and (STANDALONE_ROOT / p).is_file()})


def link(path):
    return os.path.relpath(path, 'docs').replace(os.sep, '/')


def purpose(path):
    tree = ast.parse((STANDALONE_ROOT / path).read_text())
    doc = ast.get_docstring(tree)
    if doc:
        return ' '.join(doc.splitlines()[0].split()).replace('|', '\\|')
    names = [n.name for n in tree.body if isinstance(n, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef))]
    return ('Defines ' + ', '.join('`' + n + '`' for n in names[:5]) + (', …' if len(names) > 5 else '') + '.') if names else 'Package marker / public re-exports.'


def write(name, content):
    (STANDALONE_ROOT / 'docs' / name).write_text(content.rstrip() + '\n')


def main():
    paths = files()
    runtime = [p for p in paths if p.as_posix().startswith('src/parkour_solver/') and p.suffix == '.py']
    lines = ['# Production code map', '',
             'Generated by `python -m tools.docs_index`. See [layout](LAYOUT.md) for ownership and',
             '[architecture](ARCHITECTURE.md) for execution. Production excludes tests, tools and research.', '']
    groups = defaultdict(list)
    for p in runtime:
        groups[p.parts[2] if len(p.parts) > 3 else 'public API / schema'].append(p)
    for group, members in sorted(groups.items()):
        lines += ['## ' + group, '', '| Module | Purpose |', '| --- | --- |']
        for p in members:
            lines.append(f'| [{p.relative_to("src/parkour_solver")}]({link(p)}) | {purpose(p)} |')
        lines += ['']
    for label, select in [('Native adapters', lambda p: p.parts[0] == 'native'),
                          ('Maintained developer tools', lambda p: p.parts[0] == 'tools' and p.suffix == '.py'),
                          ('Public old-namespace facades', lambda p: p.parts[0] in ('autonomy', 'ipopt') and p.suffix == '.py')]:
        lines += ['## ' + label, '', '| File | Role |', '| --- | --- |']
        for p in paths:
            if select(p):
                lines.append(f'| [{p}]({link(p)}) | {purpose(p) if p.suffix == ".py" else "Standalone Java bridge / Gradle adapter."} |')
        lines += ['']
    lines += ['## Research and data', '',
              '[Research guide](../research/README.md) separates maintained prototypes/drivers from frozen bundles.',
              '[File index](FILE_INDEX.md) lists every tracked source, test, case and artifact;',
              '[function index](FUNCTION_INDEX.md) indexes production definitions. Historical commands',
              'remain source-era evidence; use the [runbook](RUNBOOK.md) for current commands.', '']
    write('CODE_MAP.md', '\n'.join(lines))

    lines = ['# Production function index', '', 'Generated from the current installed-source tree by `python -m tools.docs_index`.',
             'Line numbers are a snapshot; symbol names are the stable lookup keys. Private helpers remain private.', '']
    for p in runtime:
        s = (STANDALONE_ROOT / p).read_text()
        definitions = []
        def visit(nodes, prefix=''):
            for n in nodes:
                if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    definitions.append((prefix + n.name, n.lineno, 'class' if isinstance(n, ast.ClassDef) else 'function'))
                    if isinstance(n, ast.ClassDef):
                        visit(n.body, prefix + n.name + '.')
        visit(ast.parse(s).body)
        if definitions:
            lines += [f'## {p.relative_to("src/parkour_solver")}', '', '| Symbol | Line | Kind |', '| --- | ---: | --- |']
            for name, number, kind in definitions:
                lines.append(f'| `{name}` | [{number}]({link(p)}#L{number}) | {kind} |')
            lines += ['']
    write('FUNCTION_INDEX.md', '\n'.join(lines))

    lines = ['# Documentation index', '', 'Generated by `python -m tools.docs_index`. User instructions and [current state](CURRENT_STATE.md)',
             'control work; inclusion here is not authorization to implement a historical plan.', '', '| Document | Status / purpose |', '| --- | --- |']
    for p in paths:
        if p.suffix != '.md':
            continue
        text = (STANDALONE_ROOT / p).read_text()
        title = next((l.lstrip('# ').strip() for l in text.splitlines() if l.startswith('# ')), p.name)
        status = ('Frozen source-era evidence; use research guide for reproduction' if p.parts[0] == 'research' and p.parts[1] not in ('route_guidance', 'legacy_cell_routes') and p.as_posix() != 'research/README.md' else
                  'Research evidence / prototype; see research guide' if p.parts[0] == 'research' else
                  'Historical; verify current authority' if 'history' in p.parts else
                  'Design contract; check decisions index for implemented/deferred scope' if 'design' in p.parts else
                  'Literature / research findings' if 'research' in p.parts else
                  'Detailed reusable contract / implementation reference' if 'reference' in p.parts else
                  'Current navigation / implementation or evidence record')
        lines.append(f'| [{p}]({link(p)}) | {status}: {title.replace("|", "/")} |')
    write('DOC_INDEX.md', '\n'.join(lines))

    groups = defaultdict(list)
    for p in paths:
        groups[p.parts[0]].append(p)
    lines = ['# Tracked standalone file index', '',
             'Generated by `python -m tools.docs_index` from Git-tracked plus new nonignored files.',
             'Ignored build products, local runs and caches are excluded. Frozen artifact bytes are',
             'verified by [layout validation](../tools/validate_layout.py), not rewritten here.', '']
    for group, members in sorted(groups.items()):
        lines += ['## ' + group, '', '| File | Bytes |', '| --- | ---: |']
        for p in members:
            lines.append(f'| [{p}]({link(p)}) | {(STANDALONE_ROOT / p).stat().st_size} |')
        lines += ['']
    write('FILE_INDEX.md', '\n'.join(lines))


if __name__ == '__main__':
    main()
